import { _electron as electron } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

const env = { ...process.env };
delete env.ELECTRON_RUN_AS_NODE;
delete env.CODYSSEY_DEV_URL;
const profile = await mkdtemp(path.join(tmpdir(), 'codyssey-canvas-controls-'));
const fixture = await mkdtemp(path.join(tmpdir(), 'codyssey-canvas-selection-'));
const sourceFile = path.join(fixture, 'example.py');
await writeFile(sourceFile, 'class Example:\n    def run(self):\n        value = 1\n        return value\n\n# outside\n');
const app = await electron.launch({ args: ['.', `--user-data-dir=${profile}`], env });
try {
  const page = await app.firstWindow();
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await app.evaluate(({ dialog }, directory) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [directory] }); }, fixture);
  await page.getByTitle('Open repository · Ctrl+O').click();
  await page.getByText('Indexed', { exact: true }).waitFor({ timeout: 60000 });
  await page.locator('.source-area .syntax-keyword').first().waitFor();
  const sourceTab = page.locator('.view-tabs').getByRole('button', { name: 'Source', exact: true });
  const add = page.locator('.breadcrumb').getByRole('button', { name: 'Add to canvas', exact: true });
  assert.equal(await add.count(), 1);
  await page.evaluate(() => {
    const first = document.querySelector('.code-line[data-line="3"] .line-content');
    const last = document.querySelector('.code-line[data-line="4"] .line-content');
    const range = document.createRange();
    range.setStart(first.firstChild.firstChild || first.firstChild, 2);
    range.setEnd(last.lastChild.firstChild || last.lastChild, 1);
    window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
  });
  await page.getByTitle('Add selected lines 3–4 to canvas').waitFor();
  await add.click();
  await page.locator('.canvas-code').waitFor();
  assert.match(await page.locator('.canvas-code-location').textContent(), /:3–4/);
  assert.doesNotMatch(await page.locator('.canvas-code-body').textContent(), /class Example|def run/);
  assert.match(await page.locator('.canvas-code-body').textContent(), /value = 1/);
  await sourceTab.click();
  // An end boundary at the beginning of line 4 must not include line 4.
  await page.evaluate(() => {
    const first = document.querySelector('.code-line[data-line="3"] .line-content');
    const next = document.querySelector('.code-line[data-line="4"] .line-content');
    const range = document.createRange(); range.setStart(first, 0); range.setEnd(next, 0);
    window.getSelection().removeAllRanges(); window.getSelection().addRange(range);
  });
  await page.getByTitle('Add selected lines 3–3 to canvas').waitFor();
  await add.click();
  assert.match(await page.locator('.canvas-code-location').last().textContent(), /:3–3/);
  await sourceTab.click();
  await page.locator('.code-line[data-line="3"] .line-number').click();
  await page.locator('.code-line[data-line="4"] .line-number').click({ modifiers: ['Shift'] });
  await page.getByTitle('Add selected lines 3–4 to canvas').waitFor();
  await add.click();
  assert.match(await page.locator('.canvas-code-location').last().textContent(), /:3–4/);
  await writeFile(sourceFile, '# heading\nclass Example:\n    def run(self):\n        value = 2\n        return value\n\n# outside\n');
  await page.waitForFunction(() => [...document.querySelectorAll('.canvas-code-body')].every((element) => element.textContent.includes('value = 2')), null, { timeout: 15000 });
  assert.match(await page.locator('.canvas-code-location').first().textContent(), /:4–5/);
  await sourceTab.click();
  await page.locator('.code-line[data-line="6"] .line-number').click();
  await add.click();
  assert.match(await page.locator('.canvas-code-location').last().textContent(), /:6–6/);
  await sourceTab.click();
  await page.locator('.code-line[data-line="1"] .line-number').click();
  await add.click();
  assert.match(await page.locator('.canvas-code').last().textContent(), /class Example/);

  const canvas = page.getByRole('region', { name: 'Free canvas', exact: true });
  const rect = await canvas.boundingBox();
  await page.evaluate(() => document.querySelector('.canvas-surface').dispatchEvent(new WheelEvent('wheel', { deltaX: -1000, bubbles: true })));
  const drag = async (locator, dx, dy) => {
    const box = await locator.boundingBox();
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2); await page.mouse.down();
    await page.mouse.move(box.x + box.width / 2 + dx, box.y + box.height / 2 + dy, { steps: 6 }); await page.mouse.up();
  };
  async function draw(tool, y) {
    await page.getByRole('button', { name: tool, exact: true }).click();
    await page.mouse.move(rect.x + 120, rect.y + y); await page.mouse.down();
    await page.mouse.move(rect.x + 300, rect.y + y, { steps: 5 }); await page.mouse.up();
  }
  const positions = async () => page.locator('.canvas-point-handle').evaluateAll((elements) => Object.fromEntries(elements.map((element) => [element.getAttribute('aria-label'), { x: parseFloat(element.style.left), y: parseFloat(element.style.top) }])));
  await draw('Bend arrow', 180);
  const start = page.getByRole('button', { name: 'Move arrow start point', exact: true });
  const end = page.getByRole('button', { name: 'Move arrow end point', exact: true });
  const middle = page.getByRole('button', { name: 'Move arrow curve point', exact: true });
  assert.equal(await middle.count(), 1);
  let before = await positions();
  assert.equal(before['Move arrow curve point'].x, (before['Move arrow start point'].x + before['Move arrow end point'].x) / 2);
  const initialPath = await page.locator('.canvas-bend .canvas-connector-hit').getAttribute('d');
  assert.match(initialPath, / Q /); assert.doesNotMatch(initialPath, / H | V /);
  await drag(middle, 0, -65);
  let after = await positions();
  assert.deepEqual(after['Move arrow start point'], before['Move arrow start point']);
  assert.deepEqual(after['Move arrow end point'], before['Move arrow end point']);
  assert.ok(after['Move arrow curve point'].y < before['Move arrow curve point'].y - 60);
  assert.notEqual(await page.locator('.canvas-bend .canvas-connector-hit').getAttribute('d'), initialPath);
  before = after;
  await drag(end, -230, 30);
  after = await positions();
  assert.deepEqual(after['Move arrow start point'], before['Move arrow start point']);
  assert.deepEqual(after['Move arrow curve point'], before['Move arrow curve point']);
  assert.ok(after['Move arrow end point'].x < after['Move arrow start point'].x);
  before = after;
  await drag(start, 25, 20);
  after = await positions();
  assert.deepEqual(after['Move arrow end point'], before['Move arrow end point']);
  assert.ok(after['Move arrow start point'].x > before['Move arrow start point'].x + 20);
  // Handles still map pointer movement correctly after zooming.
  await page.getByRole('button', { name: 'Zoom in canvas', exact: true }).click();
  before = await positions(); await drag(middle, 24, -24); after = await positions();
  assert.ok(Math.abs(after['Move arrow curve point'].x - before['Move arrow curve point'].x - 20) < 0.1);
  await draw('Arrow', 330);
  assert.equal(await middle.count(), 0);
  before = await positions(); await drag(end, 30, 30); after = await positions();
  assert.deepEqual(after['Move arrow start point'], before['Move arrow start point']);
  assert.ok(after['Move arrow end point'].x > before['Move arrow end point'].x);
  before = after; await drag(start, -30, -30); after = await positions();
  assert.deepEqual(after['Move arrow end point'], before['Move arrow end point']);
  assert.ok(after['Move arrow start point'].x < before['Move arrow start point'].x);
  await page.getByRole('button', { name: 'Undo canvas change', exact: true }).click();
  await page.getByRole('button', { name: 'Redo canvas change', exact: true }).click();
  await page.getByRole('button', { name: 'Close repository', exact: true }).click();
  await page.getByTitle('Open repository · Ctrl+O').click();
  await page.getByText('Indexed', { exact: true }).waitFor({ timeout: 60000 });
  await page.getByRole('button', { name: 'Free canvas', exact: true }).click();
  assert.equal(await page.locator('.canvas-bend').count(), 1);
  assert.notEqual(await page.locator('.canvas-bend .canvas-connector-hit').getAttribute('d'), initialPath);
  assert.deepEqual(errors, []);
  console.log('Source selection, single add action, live ranges, curved arrows, endpoint dragging, zoom, undo/redo, and persistence passed.');
} finally { await app.close(); }
